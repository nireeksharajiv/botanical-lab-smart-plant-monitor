-- Botanical Lab - Supabase Database Schema
-- Run this script in your Supabase SQL Editor (Dashboard -> SQL Editor -> New Query)

-- 1. Create table for sensor readings
CREATE TABLE IF NOT EXISTS public.readings (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  created_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL,
  soil_raw INTEGER NOT NULL,
  soil_pct DOUBLE PRECISION,
  temperature_c DOUBLE PRECISION,
  humidity_pct DOUBLE PRECISION,
  light_state TEXT NOT NULL,
  pump_on BOOLEAN NOT NULL DEFAULT false,
  mode TEXT NOT NULL DEFAULT 'NORMAL',
  problems TEXT[] NOT NULL DEFAULT '{}'::TEXT[]
);

-- Index for fetching latest reading and 24-hour time series efficiently
CREATE INDEX IF NOT EXISTS idx_readings_created_at ON public.readings (created_at DESC);

-- 2. Create table for watering history events
CREATE TABLE IF NOT EXISTS public.watering_events (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  started_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL,
  duration_seconds INTEGER NOT NULL,
  source TEXT NOT NULL CHECK (source IN ('auto', 'manual'))
);

-- Index for querying recent watering events
CREATE INDEX IF NOT EXISTS idx_watering_events_started_at ON public.watering_events (started_at DESC);

-- 3. Create table for device commands (e.g. water_now queue)
CREATE TABLE IF NOT EXISTS public.commands (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  created_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL,
  command TEXT NOT NULL,
  status TEXT NOT NULL DEFAULT 'pending' CHECK (status IN ('pending', 'done', 'rejected'))
);

-- Index for polling pending commands
CREATE INDEX IF NOT EXISTS idx_commands_status_created ON public.commands (status, created_at ASC);

-- 4. Enable Row Level Security (RLS) for data protection
-- The backend uses the SUPABASE_SERVICE_ROLE_KEY which bypasses RLS securely.
ALTER TABLE public.readings ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.watering_events ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.commands ENABLE ROW LEVEL SECURITY;
